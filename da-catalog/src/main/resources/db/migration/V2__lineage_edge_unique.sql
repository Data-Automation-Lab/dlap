-- Lineage edge uniqueness (log-derived lineage, Gap 4).
--
-- The LogEventEnrichmentListener re-derives read->write edges from the
-- high-volume normalized log stream; the same (upstream, downstream,
-- relationship) triple recurs across events. LineageService.upsertEdgeByUri
-- guards duplicates in application code, but this constraint is the durable
-- backstop against races and replays.
--
-- Postgres does not support "ADD CONSTRAINT IF NOT EXISTS", so a partial
-- unique INDEX (which does support IF NOT EXISTS) is used instead — it is
-- functionally equivalent for de-duplication and keeps this migration
-- idempotent, matching the CREATE ... IF NOT EXISTS style of V1.
CREATE UNIQUE INDEX IF NOT EXISTS uc_lineage_edge
    ON dlap_catalog.dlap_asset_lineage (upstream_asset_id, downstream_asset_id, relationship_type);
