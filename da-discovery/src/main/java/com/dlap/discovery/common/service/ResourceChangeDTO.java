package com.dlap.discovery.common.service;

import java.time.ZonedDateTime;
import java.util.Map;

/**
 * Data Transfer Object representing a change to a cloud resource.
 */
public class ResourceChangeDTO {
    private String resourceId;
    private String resourceType;
    private String changeType;
    private ZonedDateTime timestamp;
    private String description;
    private Map<String, Object> details;

    public ResourceChangeDTO() {
        // Default constructor for deserialization
    }

    public ResourceChangeDTO(String resourceId, String resourceType, String changeType,
            ZonedDateTime timestamp, String description, Map<String, Object> details) {
        this.resourceId = resourceId;
        this.resourceType = resourceType;
        this.changeType = changeType;
        this.timestamp = timestamp;
        this.description = description;
        this.details = details;
    }

    public String getResourceId() {
        return resourceId;
    }

    public void setResourceId(String resourceId) {
        this.resourceId = resourceId;
    }

    public String getResourceType() {
        return resourceType;
    }

    public void setResourceType(String resourceType) {
        this.resourceType = resourceType;
    }

    public String getChangeType() {
        return changeType;
    }

    public void setChangeType(String changeType) {
        this.changeType = changeType;
    }

    public ZonedDateTime getTimestamp() {
        return timestamp;
    }

    public void setTimestamp(ZonedDateTime timestamp) {
        this.timestamp = timestamp;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public Map<String, Object> getDetails() {
        return details;
    }

    public void setDetails(Map<String, Object> details) {
        this.details = details;
    }
}