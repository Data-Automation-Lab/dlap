package com.dlap.discovery.event.service.type;

import java.time.Instant;
import java.util.UUID;

import com.dlap.discovery.common.model.CloudResource;
import com.dlap.discovery.common.model.ResourceChange.ChangeType;
import com.dlap.discovery.crawler.model.aws.AwsProcessingJobResource;
import com.dlap.discovery.crawler.model.aws.AwsResource;
import com.dlap.discovery.crawler.model.aws.EC2Resource;
import com.dlap.discovery.crawler.model.aws.GlueResource;
import com.dlap.discovery.crawler.model.aws.RdsResource;
import com.dlap.discovery.crawler.model.aws.S3Resource;
import com.dlap.discovery.crawler.model.azure.AzureProcessingJobResource;
import com.dlap.discovery.crawler.model.azure.AzureResource;
import com.dlap.discovery.crawler.model.azure.AzureVMResource;
import com.dlap.discovery.crawler.model.databricks.DatabricksProcessingJobResource;
import com.dlap.discovery.crawler.model.gcp.BigQueryResource;
import com.dlap.discovery.crawler.model.gcp.CloudSQLResource;
import com.dlap.discovery.crawler.model.gcp.ComputeResource;
import com.dlap.discovery.crawler.model.gcp.GcpBigQueryJobResource;
import com.dlap.discovery.crawler.model.gcp.GcpResource;
import com.dlap.discovery.crawler.model.gcp.GcsResource;
import com.dlap.discovery.crawler.model.oracle.OracleResource;
import com.dlap.discovery.crawler.model.unity.UnityCatalogResource;
import com.fasterxml.jackson.annotation.JsonSubTypes;
import com.fasterxml.jackson.annotation.JsonTypeInfo;

/**
 * Event representing a resource discovery or change.
 * These events are generated by IResourceCrawler implementations and published
 * to Kafka.
 */
public class ResourceEvent {
	private String eventId;
	private Instant eventTimestamp;
	private String source;
	private String cloudProvider;
	private String accountId;
	private ChangeType changeType;

	/**
	 * The discovered resource. The wire carries a logical type name in {@code @type}, never a class
	 * name (SEC-03): the name is looked up in the closed list below, so a message cannot choose which
	 * class Jackson builds, and a name that is not listed is rejected. Every concrete
	 * {@link CloudResource} must be listed here; {@code ResourceEventTypeIdsTest} fails the build when a
	 * subclass is added without a name. A name is part of the wire contract: never reuse or rename one.
	 */
	@JsonTypeInfo(use = JsonTypeInfo.Id.NAME, include = JsonTypeInfo.As.PROPERTY, property = "@type")
	@JsonSubTypes({
			@JsonSubTypes.Type(value = AwsResource.class, name = "AWS"),
			@JsonSubTypes.Type(value = S3Resource.class, name = "AWS_S3"),
			@JsonSubTypes.Type(value = EC2Resource.class, name = "AWS_EC2"),
			@JsonSubTypes.Type(value = RdsResource.class, name = "AWS_RDS"),
			@JsonSubTypes.Type(value = GlueResource.class, name = "AWS_GLUE"),
			@JsonSubTypes.Type(value = AwsProcessingJobResource.class, name = "AWS_PROCESSING_JOB"),
			@JsonSubTypes.Type(value = AzureResource.class, name = "AZURE"),
			@JsonSubTypes.Type(value = AzureVMResource.class, name = "AZURE_VM"),
			@JsonSubTypes.Type(value = AzureProcessingJobResource.class, name = "AZURE_PROCESSING_JOB"),
			@JsonSubTypes.Type(value = GcpResource.class, name = "GCP"),
			@JsonSubTypes.Type(value = GcsResource.class, name = "GCP_GCS"),
			@JsonSubTypes.Type(value = BigQueryResource.class, name = "GCP_BIGQUERY"),
			@JsonSubTypes.Type(value = CloudSQLResource.class, name = "GCP_CLOUDSQL"),
			@JsonSubTypes.Type(value = ComputeResource.class, name = "GCP_COMPUTE"),
			@JsonSubTypes.Type(value = GcpBigQueryJobResource.class, name = "GCP_BIGQUERY_JOB"),
			@JsonSubTypes.Type(value = OracleResource.class, name = "OCI"),
			@JsonSubTypes.Type(value = UnityCatalogResource.class, name = "UNITY"),
			@JsonSubTypes.Type(value = DatabricksProcessingJobResource.class, name = "DATABRICKS")
	})
	private CloudResource payload;

	/**
	 * Default constructor for serialization.
	 */
	public ResourceEvent() {
		this.eventId = UUID.randomUUID().toString();
		this.eventTimestamp = Instant.now();
		this.source = "Crawler";
	}

	/**
	 * Constructor with required fields.
	 *
	 * @param cloudProvider The cloud provider (e.g., "AWS", "AZURE")
	 * @param accountId     The account/project ID
	 * @param changeType    The type of change (typically CREATE for crawlers)
	 * @param resource      The discovered resource
	 */
	public ResourceEvent(String cloudProvider, String accountId, ChangeType changeType, CloudResource resource) {
		this();
		this.cloudProvider = cloudProvider;
		this.accountId = accountId;
		this.changeType = changeType;
		this.payload = resource;
	}

	// Getters and setters
	public String getEventId() {
		return eventId;
	}

	public void setEventId(String eventId) {
		this.eventId = eventId;
	}

	public Instant getEventTimestamp() {
		return eventTimestamp;
	}

	public void setEventTimestamp(Instant eventTimestamp) {
		this.eventTimestamp = eventTimestamp;
	}

	public String getSource() {
		return source;
	}

	public void setSource(String source) {
		this.source = source;
	}

	public String getCloudProvider() {
		return cloudProvider;
	}

	public void setCloudProvider(String cloudProvider) {
		this.cloudProvider = cloudProvider;
	}

	public String getAccountId() {
		return accountId;
	}

	public void setAccountId(String accountId) {
		this.accountId = accountId;
	}

	public ChangeType getChangeType() {
		return changeType;
	}

	public void setChangeType(ChangeType changeType) {
		this.changeType = changeType;
	}

	public CloudResource getPayload() {
		return payload;
	}

	public void setPayload(CloudResource payload) {
		this.payload = payload;
	}

	@Override
	public String toString() {
		return "ResourceEvent{" +
				"eventId='" + eventId + '\'' +
				", eventTimestamp=" + eventTimestamp +
				", source='" + source + '\'' +
				", cloudProvider='" + cloudProvider + '\'' +
				", accountId='" + accountId + '\'' +
				", changeType=" + changeType +
				", payload=" + (payload != null ? payload.getId() : "null") +
				'}';
	}
}