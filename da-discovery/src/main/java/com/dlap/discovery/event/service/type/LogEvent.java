package com.dlap.discovery.event.service.type;

import java.time.Instant;
import java.util.UUID;

import com.dlap.discovery.common.model.ResourceChange;
import com.fasterxml.jackson.annotation.JsonSubTypes;
import com.fasterxml.jackson.annotation.JsonTypeInfo;

/**
 * Event representing a log-based resource change.
 * These events are generated by ILogAnalyzer implementations and published to
 * Kafka.
 */
public class LogEvent {

	/** The type name of a {@link ResourceChange} payload on the wire. */
	public static final String PAYLOAD_RESOURCE_CHANGE = "ResourceChange";

	private String eventId;
	private Instant eventTimestamp;
	private String source;
	private String cloudProvider;
	private String accountId;

	/**
	 * The detected change. The wire carries a logical type name in {@code @type}, never a class name
	 * (SEC-03): the name is looked up in the closed list below, so a message cannot choose which class
	 * Jackson builds. A payload without {@code @type}, as the dormant analyzers wrote it (it carried a
	 * {@code @class} that is now ignored), still reads as a {@link ResourceChange}.
	 */
	@JsonTypeInfo(use = JsonTypeInfo.Id.NAME, include = JsonTypeInfo.As.PROPERTY, property = "@type",
			defaultImpl = ResourceChange.class)
	@JsonSubTypes(@JsonSubTypes.Type(value = ResourceChange.class, name = LogEvent.PAYLOAD_RESOURCE_CHANGE))
	private ResourceChange payload;

	/**
	 * Default constructor for serialization.
	 */
	public LogEvent() {
		this.eventId = UUID.randomUUID().toString();
		this.eventTimestamp = Instant.now();
		this.source = "LogAnalyzer";
	}

	/**
	 * Constructor with required fields.
	 *
	 * @param cloudProvider The cloud provider (e.g., "AWS", "AZURE")
	 * @param accountId     The account/project ID
	 * @param change        The detected resource change
	 */
	public LogEvent(String cloudProvider, String accountId, ResourceChange change) {
		this();
		this.cloudProvider = cloudProvider;
		this.accountId = accountId;
		this.payload = change;
	}

	// Getters and setters
	public String getEventId() {
		return eventId;
	}

	public void setEventId(String eventId) {
		this.eventId = eventId;
	}

	public Instant getEventTimestamp() {
		return eventTimestamp;
	}

	public void setEventTimestamp(Instant eventTimestamp) {
		this.eventTimestamp = eventTimestamp;
	}

	public String getSource() {
		return source;
	}

	public void setSource(String source) {
		this.source = source;
	}

	public String getCloudProvider() {
		return cloudProvider;
	}

	public void setCloudProvider(String cloudProvider) {
		this.cloudProvider = cloudProvider;
	}

	public String getAccountId() {
		return accountId;
	}

	public void setAccountId(String accountId) {
		this.accountId = accountId;
	}

	public ResourceChange getPayload() {
		return payload;
	}

	public void setPayload(ResourceChange payload) {
		this.payload = payload;
	}

	@Override
	public String toString() {
		return "LogEvent{" +
				"eventId='" + eventId + '\'' +
				", eventTimestamp=" + eventTimestamp +
				", source='" + source + '\'' +
				", cloudProvider='" + cloudProvider + '\'' +
				", accountId='" + accountId + '\'' +
				", payload=" + (payload != null ? payload.getClass().getSimpleName() + ":" + payload.getId() : "null") +
				'}';
	}
}