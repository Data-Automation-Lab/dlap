package com.dlap.discovery.event.processor;

import java.util.Collections;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Component;

import com.dlap.discovery.catalog.service.ICatalogService;
import com.dlap.discovery.common.model.CloudResource;
import com.dlap.discovery.common.model.ResourceChange;
import com.dlap.discovery.common.model.ResourceChange.ChangeType;
import com.dlap.discovery.event.service.IEventSubscriber;
import com.dlap.discovery.event.service.type.ResourceEvent;

/**
 * Processor for resource events that updates the catalog.
 * Handles CREATE, UPDATE, and DELETE events.
 */
@Component
public class CatalogResourceEventProcessor implements IEventSubscriber<ResourceEvent> {
	private static final Logger log = LoggerFactory.getLogger(CatalogResourceEventProcessor.class);

	private final ICatalogService catalogService;

	@Autowired
	public CatalogResourceEventProcessor(ICatalogService catalogService) {
		this.catalogService = catalogService;
	}

	@Override
	public boolean canProcess(ResourceEvent event) {
		// Can process any resource event with a valid payload and supported change type
		if (event == null || event.getPayload() == null || event.getChangeType() == null) {
			return false;
		}

		// Check if it's a supported change type
		ChangeType changeType = event.getChangeType();
		return changeType == ChangeType.CREATE ||
				changeType == ChangeType.UPDATE ||
				changeType == ChangeType.DELETE;
	}

	@Override
	public void process(ResourceEvent event) {
		log.debug("Processing resource event in catalog: {}", event);

		try {
			CloudResource resource = event.getPayload();
			ChangeType changeType = event.getChangeType();

			switch (changeType) {
				case CREATE:
				case UPDATE:
					catalogService.updateResources(Collections.singletonList(resource));
					log.info("Updated catalog with resource: {}", resource.getResourceId());
					break;

				case DELETE:
					// For DELETE events, create a ResourceChange to represent the deletion
					ResourceChange deleteChange = createDeleteChange(event);
					catalogService.processResourceChange(deleteChange);
					log.info("Processed DELETE change for resource: {}", resource.getResourceId());
					break;

				default:
					log.warn("Unsupported change type for catalog update: {}", changeType);
					break;
			}
		} catch (Exception e) {
			log.error("Error updating catalog with resource event: {}", e.getMessage(), e);
			throw e; // Re-throw to allow parent error handling
		}
	}

	/**
	 * Creates a ResourceChange object representing a deletion.
	 * 
	 * @param event The original resource event
	 * @return A ResourceChange representing a deletion
	 */
	private ResourceChange createDeleteChange(ResourceEvent event) {
		CloudResource resource = event.getPayload();

		// Ensure resourceId is not null before creating the change
		String providerResourceId = resource.getResourceId();
		if (providerResourceId == null) {
			log.error("Cannot create DELETE change for resource with null resourceId. Event: {}", event);
			// Depending on desired behavior, either return null or throw an exception
			// Returning null might be safer to avoid breaking the processing loop
			return null; // Or throw new IllegalArgumentException(...);
		}

		ResourceChange change = new ResourceChange(
				providerResourceId, // Use the String resourceId
				resource.getResourceType(), // Pass the ResourceType record
				ChangeType.DELETE,
				event.getEventTimestamp(),
				"system" // Default actor for events generated by the system
		);

		// Set additional fields if needed and available
		change.setProjectId(event.getAccountId()); // Set project/account ID
		// change.setActor(...); // Potentially set a more specific actor if available

		return change;
	}

	@Override
	public int getPriority() {
		// Give catalog updates a high priority (lower number)
		return 10;
	}
}