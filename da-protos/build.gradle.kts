plugins {
    `java-library`
    id("com.google.protobuf") version "0.9.4"
    // Versions come from the root build (BOOT-01, ADR-0065).
    id("org.springframework.boot") apply false
    id("io.spring.dependency-management")
}

repositories {
    mavenCentral()
    google()
}

java {
    sourceCompatibility = JavaVersion.VERSION_21
    targetCompatibility = JavaVersion.VERSION_21
}

dependencyManagement {
    imports {
        mavenBom(org.springframework.boot.gradle.plugin.SpringBootPlugin.BOM_COORDINATES)
    }
}

dependencies {
    // Protobuf runtime from the Spring Boot BOM (protobuf-bom 4.35.1 with Spring Boot 4.1), the
    // version every service runs. The classes are still generated by protoc 3.25.3 below: protobuf
    // supports gencode of major version V on runtimes V and V+1 (protobuf.dev cross-version runtime
    // guarantee), and da-discovery's Google Cloud BOM pins an older 4.x runtime that newer gencode
    // would refuse (BOOT-01).
    api("com.google.protobuf:protobuf-java")
    api("com.google.protobuf:protobuf-java-util")
    
    // JPA and Database dependencies for common entities
    api("org.springframework.boot:spring-boot-starter-data-jpa")
    api("org.postgresql:postgresql")
    
    // Security dependencies for SecurityUtils
    api("org.springframework.boot:spring-boot-starter-security")
    api("org.springframework.boot:spring-boot-starter-security-oauth2-resource-server")
    
    // Validation
    api("org.springframework.boot:spring-boot-starter-validation")
    
    // JSON processing: Jackson 2, managed by the Spring Boot 4 BOM next to Jackson 3 (ADR-0066).
    api("com.fasterxml.jackson.core:jackson-databind")
    api("com.fasterxml.jackson.core:jackson-annotations")
    api("com.fasterxml.jackson.datatype:jackson-datatype-jsr310")
    
    // Utilities
    api("org.apache.commons:commons-lang3")
    implementation("javax.annotation:javax.annotation-api:1.3.2")

    // Feign API for the optional service-auth RequestInterceptor bean.
    // compileOnly: the bean is gated by @ConditionalOnClass(RequestInterceptor)
    // so it only activates in consumer services that ship Spring Cloud OpenFeign.
    // Version from the Spring Cloud BOM the root build imports.
    compileOnly("org.springframework.cloud:spring-cloud-starter-openfeign")

    // KAFKA-01: com.dlap.common.kafka.DlapKafkaFactoryBuilder builds every service's Kafka factories
    // from Spring Boot's KafkaProperties. Compile-only (Apache-2.0, Spring Boot BOM version): every
    // service that uses the builder already has spring-boot-starter-kafka at run time (root build).
    compileOnly("org.springframework.boot:spring-boot-starter-kafka")

    // Lombok for reducing boilerplate (optional but recommended)
    compileOnly("org.projectlombok:lombok")
    annotationProcessor("org.projectlombok:lombok")
    
    // Testing dependencies
    testImplementation("org.springframework.boot:spring-boot-starter-test")
    // JUnit 6 (Spring Boot 4 BOM) needs its launcher on the test runtime classpath; Gradle no longer
    // supplies a matching one. The Spring Boot plugin adds it to the service modules (BOOT-01).
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
    testImplementation("org.testcontainers:testcontainers-postgresql")
    testImplementation("org.testcontainers:testcontainers-junit-jupiter")
    // KAFKA-01: the builder's tests bind real KafkaProperties and run an embedded broker (no Docker).
    testImplementation("org.springframework.boot:spring-boot-starter-kafka")
    testImplementation("org.springframework.boot:spring-boot-starter-kafka-test")
    // Lifecycle State 0.1: validates docs/specs/examples/lifecycle-state against its JSON Schema
    // (draft 2020-12). Test scope only. Apache-2.0; same version as da-logingest's schema test.
    testImplementation("com.networknt:json-schema-validator:1.4.0")
}

protobuf {
    protoc {
        // The version of protoc must match protobuf-java. Or use a toolchain.
        artifact = "com.google.protobuf:protoc:3.25.3"
    }
    
    generateProtoTasks {
        all().forEach { task ->
            // Configure output for generated Java files
            task.builtins {
                java {
                    // Standard Java generation
            }
        }
            
            // Ensure Google well-known types are available
            task.dependsOn("extractIncludeProto")
        }
    }
}

// Configure source sets for both proto and java
sourceSets {
    main {
        java {
            srcDirs("src/main/java", "build/generated/source/proto/main/java")
        }
        resources {
            srcDir("src/main/resources")
        }
    }
    test {
        java {
            srcDir("src/test/java")
        }
        resources {
            srcDir("src/test/resources")
        }
    }
}

// Ensure generated sources are cleaned
tasks.named("clean", Delete::class) {
    delete("build/generated")
}

// Exclude .proto files from being processed by the default resources task,
// as they are handled by the protobuf plugin.
tasks.withType<ProcessResources> {
    duplicatesStrategy = DuplicatesStrategy.EXCLUDE
    exclude("**/*.proto")
}

// Configure compilation order
tasks.withType<JavaCompile> {
    dependsOn(tasks.named("generateProto"))
} 

 